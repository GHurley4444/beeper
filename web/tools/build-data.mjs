// Pulls the card pools, tool text, songs and boot logo out of the firmware
// sources so the web app and the ESP32 share one copy of the content.
//
//   node web/tools/build-data.mjs
//
// Writes web/data.js and web/img/logo.png. Re-run after editing the .ino/.h files.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { deflateSync, crc32 } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(web, '..');
const read = (f) => readFileSync(join(repo, f), 'utf8');

// Drop // and /* */ comments without touching string contents ("https://...").
function stripComments(src) {
  let out = '', i = 0, inStr = false;
  while (i < src.length) {
    const c = src[i], n = src[i + 1];
    if (inStr) {
      out += c;
      if (c === '\\') { out += n; i += 2; continue; }
      if (c === '"') inStr = false;
      i++;
    } else if (c === '"') { inStr = true; out += c; i++; }
    else if (c === '/' && n === '/') { while (i < src.length && src[i] !== '\n') i++; }
    else if (c === '/' && n === '*') { i = src.indexOf('*/', i + 2) + 2; }
    else { out += c; i++; }
  }
  return out;
}

const strings = (body) => [...body.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => JSON.parse(`"${m[1]}"`));

function arrays(src) {
  const map = {};
  const re = /const\s+(?:char\s*\*|TarotCard)\s*(\w+)\s*\[[^\]]*\]\s*=\s*\{([\s\S]*?)\};/g;
  for (const m of stripComments(src).matchAll(re)) map[m[1]] = strings(m[2]);
  return map;
}

const ino = read('beeper.ino'), tools = read('tools.h'), songsH = read('songs.h');
const A = { ...arrays(ino), ...arrays(tools), ...arrays(songsH) };
const need = (name) => {
  if (!A[name]) throw new Error(`array ${name} not found in firmware sources`);
  return A[name];
};

// Generator pools: <menu><Part><Easy|Norm|Hard>
const tiers = (prefix) => ({ easy: need(prefix + 'Easy'), normal: need(prefix + 'Norm'), hard: need(prefix + 'Hard') });
const gen = {
  game: { cond: tiers('gameCond'), obj: tiers('gameObj'), close: tiers('gameClose') },
  city: {
    cond: tiers('cityCond'), act1: tiers('cityAct1'), adj: tiers('cityAdj'),
    noun: tiers('cityNoun'), act2: tiers('cityAct2'), close: tiers('cityClose'),
  },
  con: { cond: tiers('conCond'), act1: tiers('conAct1'), act2: tiers('conAct2'), close: tiers('conClose') },
  task: { cond: tiers('taskCond'), obj: tiers('taskObj'), close: tiers('taskClose') },
};

// Song catalogue: { "TITLE", arrayName, COUNT }
const catBody = stripComments(ino).match(/songCatalogue\[\]\s*=\s*\{([\s\S]*?)\};/)[1];
const songs = [...catBody.matchAll(/\{\s*"([^"]+)"\s*,\s*(\w+)/g)].map(([, title, arr]) => ({ title, lines: need(arr) }));

const tarotFlat = need('TAROT');
const tarot = [];
for (let i = 0; i < tarotFlat.length; i += 2) tarot.push({ name: tarotFlat[i], desc: tarotFlat[i + 1] });

const data = {
  idle: need('idleTexts'),
  rare: [need('rareGame'), need('rareCity'), need('rareCon'), need('rareTask')],
  rewards: [
    [need('coreRewards'), need('corePunishments')],
    [need('cityRewards'), need('cityPunishments')],
    [need('conRewards'), need('conPunishments')],
    [need('taskRewards'), need('taskPunishments')],
  ],
  gen,
  games: need('GAME_LIST'),
  tarot,
  oracle: need('ORACLE_RESPONSES'),
  words: { NOUN: need('GEN_NOUNS'), ADJ: need('GEN_ADJECTIVES'), VERB: need('GEN_VERBS'), NAME: need('GEN_NAMES') },
  songs,
};

writeFileSync(
  join(web, 'data.js'),
  `// Generated by tools/build-data.mjs from the firmware sources. Do not edit by hand.\nexport default ${JSON.stringify(data)};\n`,
);

// Logo: RGB565 320x96 -> RGBA, black (0x0000) becomes transparent.
const px = [...stripComments(read('index.h')).matchAll(/0x([0-9A-Fa-f]{4})/g)].map((m) => parseInt(m[1], 16));
const W = 320, H = 96;
if (px.length !== W * H) throw new Error(`logo has ${px.length} pixels, expected ${W * H}`);
const logo = new Float32Array(W * H * 4);
px.forEach((p, i) => {
  logo.set([((p >> 11) & 31) * 255 / 31, ((p >> 5) & 63) * 255 / 63, (p & 31) * 255 / 31, p ? 255 : 0], i * 4);
});

function png(w, h, rgba) {
  const raw = Buffer.alloc(h * (1 + w * 4));
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w * 4; x++) raw[y * (1 + w * 4) + 1 + x] = Math.round(rgba[y * w * 4 + x]);
  }
  const chunk = (type, body) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(body.length);
    const tb = Buffer.concat([Buffer.from(type), body]);
    const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(tb));
    return Buffer.concat([len, tb, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 6; // 8-bit RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw)), chunk('IEND', Buffer.alloc(0)),
  ]);
}

mkdirSync(join(web, 'img'), { recursive: true });
writeFileSync(join(web, 'img', 'logo.png'), png(W, H, logo));

// Home-screen icons: the emblem's bounding box, scaled bilinearly onto an opaque
// square in the app background colour (iOS ignores transparency in icons).
let x0 = W, y0 = H, x1 = 0, y1 = 0;
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
  if (logo[(y * W + x) * 4 + 3]) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
}
const BG = [15, 15, 15];
function icon(size, fill) {
  const out = new Float32Array(size * size * 4);
  const box = Math.max(x1 - x0 + 1, y1 - y0 + 1), scale = (size * fill) / box;
  const ox = (size - (x1 - x0 + 1) * scale) / 2, oy = (size - (y1 - y0 + 1) * scale) / 2;
  const at = (x, y, c) => (x < x0 || x > x1 || y < y0 || y > y1 ? 0 : logo[(y * W + x) * 4 + c]);
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const sx = (x - ox) / scale + x0 - 0.5, sy = (y - oy) / scale + y0 - 0.5;
    const ix = Math.floor(sx), iy = Math.floor(sy), fx = sx - ix, fy = sy - iy;
    const lerp = (c) => (at(ix, iy, c) * (1 - fx) + at(ix + 1, iy, c) * fx) * (1 - fy)
      + (at(ix, iy + 1, c) * (1 - fx) + at(ix + 1, iy + 1, c) * fx) * fy;
    const a = lerp(3) / 255, o = (y * size + x) * 4;
    // Colour channels are premultiplied by alpha in the lerp, so composite directly.
    for (let c = 0; c < 3; c++) out[o + c] = Math.min(255, lerp(c) + BG[c] * (1 - a));
    out[o + 3] = 255;
  }
  return png(size, size, out);
}
for (const s of [180, 192, 512]) writeFileSync(join(web, 'img', `icon-${s}.png`), icon(s, 0.7));

const pools = Object.values(gen).flatMap((m) => Object.values(m).flatMap((t) => Object.values(t))).length;
console.log(`data.js: ${pools} generator pools, ${tarot.length} tarot cards, ${songs.length} songs, ${data.games.length} games`);
console.log('img/logo.png: 320x96');
